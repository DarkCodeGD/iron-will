"""Owns the background ``cava`` process and turns its raw stream into frames.

Instead of a FIFO in /tmp we point cava's raw output at its own stdout and read
the pipe: no stale FIFO files, no clashes between instances, no blocking
``open()`` handshake, and EOF tells us immediately when cava dies.

Wire format (``data_format=binary``, ``bit_format=16bit``): each frame is
``bars`` native-endian uint16 values (0–65535), back to back, no separators.
We read whatever is available and keep only the *newest* complete frame —
dropping stale frames keeps latency at about one frame.

Lifecycle safety: cava is started under ``setpriv --pdeathsig TERM`` so the
kernel kills it if we die abruptly (segfault, SIGKILL) — no orphaned cava
eating CPU in the background.
"""

from __future__ import annotations

import ctypes
import logging
import os
import re
import shutil
import signal
import subprocess
import time

from PySide6.QtCore import QObject, QSocketNotifier, QTimer, Signal

from .. import paths

log = logging.getLogger("iron_will.cava")

_INV_MAX = 1.0 / 65535.0
# Distro builds differ (Fedora's cava has no PipeWire input). In "auto" mode we
# walk this list, moving on when cava reports the backend wasn't compiled in.
AUTO_INPUTS = ("pipewire", "pulse")
_MISSING_INPUT = re.compile(r"built without '(\w+)' input support")
_PR_SET_PDEATHSIG = 1

CAVA_CONFIG = """\
# Generated by Iron Will on every start — edit ~/.config/iron-will/config.toml instead.
[general]
bars = {bars}
framerate = {fps}
autosens = {autosens}
sensitivity = {sensitivity}
lower_cutoff_freq = {low}
higher_cutoff_freq = {high}
sleep_timer = 3

[input]
method = {method}
source = auto

[output]
method = raw
raw_target = /dev/stdout
data_format = binary
bit_format = 16bit
channels = mono
mono_option = average

[smoothing]
noise_reduction = {noise}
monstercat = 0
waves = 0
"""


def _pdeathsig_preexec() -> None:  # fallback when setpriv is missing
    ctypes.CDLL(None).prctl(_PR_SET_PDEATHSIG, signal.SIGTERM, 0, 0, 0)


class CavaProcess(QObject):
    frame = Signal(list)  # list[float] in 0..1

    def __init__(self, parent: QObject | None = None) -> None:
        super().__init__(parent)
        self._proc: subprocess.Popen | None = None
        self._notifier: QSocketNotifier | None = None
        self._log_file = None
        self._buffer = bytearray()
        self._bars = 0
        self._settings: tuple[int, int, dict] | None = None
        self._stopping = False
        self._started_at = 0.0
        self._backoff_ms = 1000
        self._missing_logged = False
        self._method = ""
        self._unsupported: set[str] = set()   # inputs this cava build lacks
        self._restart_timer = QTimer(self)
        self._restart_timer.setSingleShot(True)
        self._restart_timer.timeout.connect(self._spawn)

    def start(self, bars: int, fps: int, analysis: dict) -> None:
        """(Re)start cava with new settings."""
        self.stop()
        self._settings = (bars, fps, analysis)
        self._stopping = False
        self._backoff_ms = 1000
        self._spawn()

    def stop(self) -> None:
        self._stopping = True
        self._restart_timer.stop()
        self._teardown_notifier()
        proc, self._proc = self._proc, None
        if proc and proc.poll() is None:
            proc.terminate()
            try:
                proc.wait(timeout=1.5)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
        if proc and proc.stdout:
            proc.stdout.close()
        if self._log_file:
            self._log_file.close()
            self._log_file = None

    # ── internals ─────────────────────────────────────────────────────────
    def _spawn(self) -> None:
        if self._settings is None:
            return
        exe = shutil.which("cava")
        if not exe:
            if not self._missing_logged:
                log.error("cava is not installed — the visualizer stays idle (retrying every 15s)")
                self._missing_logged = True
            self._restart_timer.start(15_000)
            return
        self._missing_logged = False

        bars, fps, a = self._settings
        low = a["low_cutoff"]
        high = max(a["high_cutoff"], low + 500)  # cava refuses low >= high
        requested = a.get("input", "auto")
        if requested == "auto":
            candidates = [m for m in AUTO_INPUTS if m not in self._unsupported]
            self._method = candidates[0] if candidates else AUTO_INPUTS[-1]
        else:
            self._method = requested
        conf = paths.runtime_dir() / "cava.conf"
        conf.write_text(CAVA_CONFIG.format(
            method=self._method, bars=bars, fps=fps, autosens=int(a["autosens"]), sensitivity=a["sensitivity"],
            low=low, high=high, noise=a["noise_reduction"]))

        cmd = [exe, "-p", str(conf)]
        kwargs: dict = {}
        if setpriv := shutil.which("setpriv"):
            cmd = [setpriv, "--pdeathsig", "TERM", "--", *cmd]
        else:
            kwargs["preexec_fn"] = _pdeathsig_preexec
        if self._log_file:  # don't leak one fd per restart
            self._log_file.close()
        self._log_file = open(paths.runtime_dir() / "cava.log", "wb")
        try:
            self._proc = subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                          stderr=self._log_file, bufsize=0, **kwargs)
        except OSError as exc:
            log.error("could not start cava: %s", exc)
            self._schedule_restart()
            return

        self._bars = bars
        self._buffer.clear()
        self._started_at = time.monotonic()
        fd = self._proc.stdout.fileno()
        os.set_blocking(fd, False)
        self._notifier = QSocketNotifier(fd, QSocketNotifier.Type.Read, self)
        self._notifier.activated.connect(self._on_readable)
        log.info("cava started: %d bars @ %d fps, %s input", bars, fps, self._method)

    def _on_readable(self, *_args) -> None:
        if not self._proc:
            return
        try:
            chunk = os.read(self._proc.stdout.fileno(), 1 << 16)
        except BlockingIOError:
            return
        except OSError:
            chunk = b""
        if not chunk:  # EOF → cava exited
            self._on_exit()
            return
        buf = self._buffer
        buf.extend(chunk)
        frame_size = self._bars * 2
        complete = len(buf) // frame_size
        if not complete:
            return
        end = complete * frame_size
        newest = bytes(buf[end - frame_size:end])
        del buf[:end]
        self.frame.emit([v * _INV_MAX for v in memoryview(newest).cast("H")])

    def _on_exit(self) -> None:
        self._teardown_notifier()
        proc, self._proc = self._proc, None
        code = proc.wait() if proc else None
        if proc and proc.stdout:
            proc.stdout.close()
        if self._stopping:
            return
        log_path = paths.runtime_dir() / "cava.log"
        try:
            reason = log_path.read_text(errors="replace").strip()
        except OSError:
            reason = ""
        missing = _MISSING_INPUT.search(reason)
        if missing and self._settings and self._settings[2].get("input", "auto") == "auto" \
                and missing.group(1) not in self._unsupported:
            self._unsupported.add(missing.group(1))
            log.info("this cava build has no %s input — falling back", missing.group(1))
            self._restart_timer.start(0)  # immediate retry with the next input
            return
        log.warning("cava exited (code %s): %s", code, reason.splitlines()[-1] if reason else f"see {log_path}")
        self._schedule_restart()

    def _schedule_restart(self) -> None:
        # Exponential backoff, reset once cava has run healthily for a while.
        if time.monotonic() - self._started_at > 10:
            self._backoff_ms = 1000
        log.info("restarting cava in %.0fs", self._backoff_ms / 1000)
        self._restart_timer.start(self._backoff_ms)
        self._backoff_ms = min(self._backoff_ms * 2, 30_000)

    def _teardown_notifier(self) -> None:
        if self._notifier:
            self._notifier.setEnabled(False)
            self._notifier.deleteLater()
            self._notifier = None
